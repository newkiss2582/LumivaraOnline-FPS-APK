const fs=require('fs'),assert=require('assert'),path=require('path');
const root=path.resolve(__dirname,'..'),src=path.join(root,'src/com/lumivaraonline/fps');
const read=n=>fs.readFileSync(path.join(src,n),'utf8');
const manifest=fs.readFileSync(path.join(root,'AndroidManifest.xml'),'utf8');
assert(manifest.includes('package="com.lumivaraonline.fps"'));
assert.equal((manifest.match(/<service /g)||[]).length,1);
assert(!manifest.includes('android:process=')&&!manifest.includes('ProfileComponents$'));
assert.equal((manifest.match(/\.GameFullscreenActivity"/g)||[]).length,1);
assert(!read('ProfileComponents.java').includes('Service1'));
const main=read('MainActivity.java'),service=read('FloatingGameService.java'),fullscreen=read('GameFullscreenActivity.java');
assert(!/open_all_profiles|select_profile|WindowArranger|manage_windows/.test(main+service));
assert(service.includes('if(FULLSCREEN.equals(action)){expand();openFullscreen();}'));
assert(!service.includes('diagnostics.start()')&&!read('GameDiagnostics.java').includes('handler.postDelayed(sampler'));
assert(service.includes('fullscreenViewport.setRenderScale')&&read('MiniGameLayout.java').includes('RenderGeometry.size'));
assert(fullscreen.includes('requestRefreshRate(false)'));
assert(service.includes('interactive&&expanded&&fullscreenActivity==null'));
assert(read('PerformanceSettings.java').includes('Build.VERSION.SDK_INT>=34'));
assert(!/setLayerType\([^\n]*SOFTWARE/.test(service));
assert(!/setUserAgentString|addJavascriptInterface|onReceivedSslError/.test(service),'no insecure engine or auth workaround');
console.log('PASS: one registered game service/host, isolated app identity, no multi-window UI, fullscreen startup, hardware renderer, on-demand diagnostics and display-request release contracts.');
